import { ApiProperty } from '@nestjs/swagger';
import { ProjectIncomeDto } from './project-income.dto';

/**
 * DTO representing the income response for a specific month.
 */
export class IncomeResponseDto {
  @ApiProperty({
    example: 1234567.89,
    description: 'Total income generated by the corporation',
  })
  totalIncome!: number;

  @ApiProperty({
    example: 86419.7,
    description: 'Total profit generated by the corporation',
  })
  totalProfit!: number;

  @ApiProperty({
    description: 'List of incomes grouped by project',
    type: [ProjectIncomeDto],
  })
  projectIncomes!: ProjectIncomeDto[];
}
