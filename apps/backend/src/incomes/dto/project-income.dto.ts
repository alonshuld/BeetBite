import { ApiProperty } from '@nestjs/swagger';

/**
 * DTO representing the income details for a specific project.
 */
export class ProjectIncomeDto {
  @ApiProperty({
    example: 'proj-123e4567-e89b-12d3-a456-426614174000',
    description: 'Unique identifier for the project',
  })
  projectId!: string;

  @ApiProperty({
    example: 'Campus Nvidia',
    description: 'Name of the project',
  })
  projectName!: string;

  @ApiProperty({
    example: 123456.78,
    description:
      'The amount of money paid by the client for the work on the project this month',
  })
  income!: number;

  @ApiProperty({
    example: 7,
    description: 'Profit margin of the project',
    maximum: 100,
    minimum: 0,
  })
  profitMargin!: number;

  @ApiProperty({
    example: 8641.97,
    description: 'Total profit generated by the project',
  })
  profit!: number;
}
